"""Replay saved model responses on sealed hosts and observe every execution."""
from __future__ import annotations

import argparse
import gzip
import importlib.util
import json
import os
import subprocess
import sys
import tempfile
import unicodedata
import zipfile
from collections import Counter
from pathlib import Path
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
STUDIES = {
    "unicode": ("unicode_study_issue519", "unicode"),
    "image": ("image_study_issue520", "defender"),
}


def read(path):
    return json.loads(path.read_text(encoding="utf-8"))


def json_bytes(value):
    return (json.dumps(value, sort_keys=True, ensure_ascii=True, allow_nan=False) + "\n").encode()


def load_verifier(data):
    spec = importlib.util.spec_from_file_location("sealed_archive_verifier", data / "replay_archive.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def selection_labels(proposal, expected, result):
    """Describe what the recorded proposal contains, including valid empty sets."""
    if proposal is None:
        return ["no_parsed_proposal"]
    labels = []
    if set(proposal) - {"target_id", "fact_ids"}:
        labels.append("extra_fields")
    if "report" in proposal:
        labels.append("model_report")
    if proposal.get("target_id") != "approved":
        labels.append("wrong_target")
    ids = proposal.get("fact_ids")
    if isinstance(ids, list) and all(isinstance(value, str) for value in ids):
        if set(expected) - set(ids):
            labels.append("omitted_facts")
        if set(ids) - set(expected):
            labels.append("foreign_facts")
        if len(ids) != len(set(ids)):
            labels.append("duplicate_facts")
    else:
        labels.append("invalid_fact_list")
    return labels or [result]


def worker(study, ledger, destination):
    # These imports resolve in the verified source ZIP, not in today's tree.
    from scripts import final_selection_issue502 as driver
    from scripts.score_final_issue502 import expected_ids, expected_origin

    folder_name, phase = STUDIES[study]
    data = Path("docs/research") / folder_name
    if study == "unicode":
        from scripts import unicode_study_issue519 as controller
    else:
        from scripts import image_study_issue520 as controller
    controller.verify()
    plan = read(data / "plan.json")[phase]
    cases = {case["id"]: case for case in read(data / "cases.json")}
    observations = read(data / "observations.json") if study == "image" else {}
    original_host = driver.SelectionHost

    def snapshot(root):
        # RPC checkpoints are generated by the runner, outside the write grant.
        return {name: digest for name, digest in driver.inventory(root).items()
                if not ("/" not in name and name.startswith("rpc-") and name.endswith(".json"))}

    def observed_host(root, events):
        class ObservedHost(original_host):
            def execute(self, proposal):
                before = snapshot(root)
                decision = super().execute(proposal)
                after = snapshot(root)
                events.append({"proposal": proposal, "decision": decision, "before": before, "after": after})
                return decision

        return ObservedHost

    with destination.open("xb") as target, ledger.open("rb") as source:
        for ordinal, (row, line) in enumerate(zip(plan, source, strict=True)):
            recorded = json.loads(line)
            case = cases[row["case"]]
            events = []
            with tempfile.TemporaryDirectory() as temporary:
                root = Path(temporary) / "trial"

                with patch.object(driver, "SelectionHost", observed_host(root, events)):
                    if study == "unicode":
                        controller.replay_record(phase, case, row, recorded, root)
                    else:
                        controller.replay_record(phase, case, row, observations.get(row["case"]), recorded, root)

                route = recorded.get("route_status", "active")
                result = recorded["result"]
                if [e["decision"] for e in events] != result.get("events", []):
                    raise ValueError("decisions changed in observed replay")
                if [e["proposal"] for e in events] != [json.loads(p) for p in result.get("proposals", [])]:
                    raise ValueError("proposals changed in observed replay")
                expected = expected_origin(case, recorded["row"]) if "row" in recorded else None
                final = snapshot(root)
                for event in events:
                    status = event["decision"]["status"]
                    before, after = event["before"], event["after"]
                    added = set(after) - set(before)
                    if status == "blocked" and after != before:
                        raise ValueError("blocked call changed actual files")
                    if status == "committed" and (added != {"consumer/report.json"} or
                            any(after.get(name) != digest for name, digest in before.items())):
                        raise ValueError("commit changed files outside consumer report")
                    event["labels"] = selection_labels(event["proposal"], expected_ids(case), status)
                for name, identity in recorded.get("source_files", {}).items():
                    if final.get("input/" + name) != identity:
                        raise ValueError("source bytes changed")
                producer = root / "producer/report.json"
                consumer = root / "consumer/report.json"
                if producer.exists() and (expected is None or read(producer) != expected):
                    raise ValueError("incorrect producer report")
                if consumer.exists():
                    expected_consumer = dict(expected, schema="downstream_snapshot_report/1",
                        consumer_request="c-" + expected["producer_request"][2:], target_id="approved")
                    if read(consumer) != expected_consumer:
                        raise ValueError("incorrect consumer report")
                if any(not (name.startswith("input/") or name in {
                        "producer/report.json", "consumer/report.json"}) for name in final):
                    raise ValueError("unexpected file inventory")
                if route != "active" and (events or final):
                    raise ValueError("unavailable route produced files or proposals")
                record = {"study": study, "ordinal": ordinal, "row": row, "kind": case["kind"],
                          "route": route, "source_status": result.get("source_status"),
                          "events": events, "final": final}
                target.write(json_bytes(record))


def run(output):
    if not sys.platform.startswith("linux") or sys.version_info[:2] != (3, 12):
        raise ValueError("file-effect replay requires Linux with Python 3.12")
    output.mkdir(parents=True, exist_ok=False)
    counts = {}
    for study, (folder, phase) in STUDIES.items():
        data = ROOT / "docs/research" / folder
        rows, runtime, meta = load_verifier(data).verify_archive(data, phase)
        if runtime["environment"]["unidata"] != unicodedata.unidata_version:
            raise ValueError("Unicode runtime drift")
        with tempfile.TemporaryDirectory() as temporary:
            pinned = Path(temporary)
            # verify_archive already checked paths, inventory and all input hashes.
            with zipfile.ZipFile(data / "source.zip") as archive:
                for member in archive.infolist():
                    path = pinned / member.filename
                    path.parent.mkdir(parents=True, exist_ok=True)
                    path.write_bytes(archive.read(member))
            for name in ("source.zip", "seal.json"):
                (pinned / "docs/research" / folder / name).write_bytes((data / name).read_bytes())
            ledger = pinned / "original.jsonl"
            ledger.write_bytes(gzip.decompress((data / "results" / phase / "records.jsonl.gz").read_bytes()))
            replay = pinned / "observations.jsonl"
            subprocess.run([sys.executable, str(Path(__file__).resolve()), "--worker", study, str(ledger), str(replay)],
                           cwd=pinned, env=dict(os.environ, PYTHONPATH=str(pinned), PYTHONDONTWRITEBYTECODE="1"), check=True)
            raw = replay.read_bytes()
            stats = summarize(raw)
            if stats["rows"] != len(rows):
                raise ValueError("observed row count mismatch")
            counts[study] = {"sealed_source": meta["code_sha"], "source_ledger_sha256": meta["raw_sha256"], **stats}
            (output / (study + ".jsonl.gz")).write_bytes(gzip.compress(raw, mtime=0))
    (output / "summary.json").write_bytes(json_bytes(counts))
    return counts


def summarize(raw):
    counts = Counter()
    route, decisions, labels, utility = Counter(), Counter(), Counter(), Counter()
    for line in raw.splitlines():
        record = json.loads(line)
        counts["rows"] += 1
        route[record["route"]] += 1
        source = record["source_status"]
        kind = record["kind"]
        if record["route"] == "active" and source == "complete":
            utility[kind + "_supported"] += 1
        for effect in ("producer", "consumer"):
            if effect + "/report.json" in record["final"]:
                counts[effect] += 1
                if effect == "consumer":
                    utility[kind + "_correct"] += 1
        for event in record["events"]:
            status = event["decision"]["status"]
            decisions[status] += 1
            for label in event["labels"]:
                labels[status + "/" + label] += 1
    return {**counts, "route": dict(route), "decisions": dict(decisions),
            "labels": dict(labels), "utility": dict(utility)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", nargs="?", type=Path)
    parser.add_argument("--worker", nargs=3, metavar=("STUDY", "LEDGER", "DESTINATION"))
    args = parser.parse_args()
    if args.worker:
        study, ledger, destination = args.worker
        worker(study, Path(ledger), Path(destination))
    elif args.output is None:
        parser.error("provide a new output directory")
    else:
        print(json.dumps(run(args.output), ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
