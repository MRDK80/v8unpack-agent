"""form_classifier — классификатор форм 1С: объектные vs. сервисные.

Решает issue #98: формы-мастера, помощники и диалоги привязывают поля
не к реквизитам объекта метаданных (``Объект.Реквизит``), а к временным
реквизитам формы. Это не баг парсера — архитектурный паттерн платформы 1С.

Классы форм
------------------
:data:`FormClass.OBJECT`
    Объектная форма: поля привязаны к реквизитам объекта (``Объект.*``).
    Включается в агрегированное покрытие data_path.

:data:`FormClass.SERVICE`
    Сервисная форма (мастер, помощник, диалог, информационная): поля привязаны
    к временным реквизитам формы или отсутствуют вовсе.
    Исключается из агрегированного покрытия или считается отдельно.

:data:`FormClass.UNKNOWN`
    Класс не определён. Возникает в двух случаях:
    элементов формы нет вообще, либо elem_parser не смог извлечь разметку.

Критерий классификации
------------------------
Критерий двойной, объединяется через OR:

1. **По имени**: имя формы начинается с одного из паттернов
   из :data:`SERVICE_FORM_NAME_PATTERNS` (регистронезависимо).

2. **По структуре**:
   - data-элементы есть И ни одного ``data_path`` не начинается с
     ``Объект.`` (регистронезависимо) → SERVICE;
   - data-элементов нет вовсе → SERVICE
     (информационная/навигационная форма без полей данных);
   - хотя бы один ``data_path`` начинается с ``Объект.`` → OBJECT.

Форма считается SERVICE если выполняется хотя бы одно условие.

Формы с пустым tree
--------------------
Отдельный случай: ``.elem.json`` содержит ``tree: []``. Верификация на
production (2231 форма) показала, что пустой tree НЕ означает сервисную
форму — среди таких форм встречаются ``ФормаЗаписи`` регистров сведений
и основные формы отчётов/обработок ``Форма``. Это объектные формы,
разметку которых elem_parser не смог распарсить.

Поэтому :func:`classify_empty_tree_form` возвращает SERVICE только при
совпадении с проверенным списком :data:`SERVICE_FORM_NAME_PATTERNS`.
Во всех остальных случаях — UNKNOWN с диагностической причиной.
Классификатор не должен придумывать класс, когда парсер не предоставил
структуру формы: ложное отнесение объектной формы к SERVICE исключило бы
её из метрики покрытия и скрыло реальную проблему парсера.

Формы без виджетов данных (NO_TABULAR_NO_WIDGETS)
--------------------------------------------------
Отдельный случай: ``classify_unindexed_form`` вернул
``UnindexedReason.NO_TABULAR_NO_WIDGETS`` — legacy JSON читается, но не
содержит ни TabularField, ни InputField/ComboBox. В отличие от пустого
тree, здесь отсутствие виджетов **структурно подтверждено** парсером.

:func:`classify_no_widgets_form` использует это дополнительное условие,
чтобы безопасно выдавать SERVICE для форм с именами из
:data:`EMPTY_TREE_NAME_HINTS` или :data:`SERVICE_FORM_NAME_PATTERNS`:
визуальная проверка 17 production-форм подтвердила, что все они —
диалоги, информационные и настроечные формы без полей данных.

OS-нейтральность, кодировка UTF-8.
"""
from __future__ import annotations

from typing import Iterable

