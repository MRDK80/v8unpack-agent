# ---------------------------------------------------------------------------
# FormClass — возвращаемые значения
# ---------------------------------------------------------------------------

class FormClass(str):
    """String-совместимые константы класса формы.

    Используется как str (сериализуется напрямую), но позволяет сравнение
    через FormClass.OBJECT, FormClass.SERVICE и FormClass.UNKNOWN.
    """

    OBJECT: "FormClass"
    SERVICE: "FormClass"
    UNKNOWN: "FormClass"

    def __new__(cls, value: str) -> "FormClass":
        return super().__new__(cls, value)


FormClass.OBJECT = FormClass("object")
FormClass.SERVICE = FormClass("service")
FormClass.UNKNOWN = FormClass("unknown")


# ---------------------------------------------------------------------------
# Классификация по имени
# ---------------------------------------------------------------------------

def classify_form_by_name(form_name: str) -> FormClass:
    """Cклассифицировать форму по имени.

    Возвращает :data:`FormClass.SERVICE` если имя начинается
    (регистронезависимо) с одного из :data:`SERVICE_FORM_NAME_PATTERNS`.
    Иначе — :data:`FormClass.UNKNOWN` (не хватает данных для определения).

    Параметры
    ----------
    form_name:
        Короткое имя формы (leaf-часть пути, например ``ПомощникПодключенияЭДО``).
    """
    if not form_name:
        return FormClass.UNKNOWN

    lower_name = form_name.lower()

    for pattern in SERVICE_FORM_NAME_PATTERNS:
        if lower_name.startswith(pattern):
            return FormClass.SERVICE

    return FormClass.UNKNOWN


def classify_empty_tree_form(form_name: str) -> tuple[FormClass, str]:
    """Cклассифицировать форму, элементы которой не удалось извлечь.

    Пустой ``tree`` в ``.elem.json`` не означает сервисную форму. Это может
    быть как платформенный диалог, так и обычная объектная форма, разметку
    которой elem_parser не распарсил. Верификация на production подтвердила
    второй случай: ``ФормаЗаписи`` регистров сведений и основные формы
    ``Форма`` отчётов приходят с пустым tree.

    Возвращает пару ``(класс, причина)``. Причина — машиночитаемый код
    для диагностики в verify-скриптах и отчётах.

    Коды причин
    -----------
    ``no_name``
        Имя формы не передано.
    ``by_service_pattern``
        Имя начинается с проверенного паттерна
        из :data:`SERVICE_FORM_NAME_PATTERNS`. Единственный случай,
        когда возвращается SERVICE.
    ``platform_object_name_unparsed``
        Имя совпадает со стандартной объектной формой платформы.
        Указывает на пробел в elem_parser — требует внимания.
    ``empty_tree_name_hint``
        Имя похоже на сервисное (:data:`EMPTY_TREE_NAME_HINTS`),
        но без разметки подтвердить нельзя.
    ``unparsed_empty_tree``
        Имя не распознано, разметки нет.

    Параметры
    ----------
    form_name:
        Короткое имя формы (лист-часть пути).
    """
    if not form_name:
        return FormClass.UNKNOWN, "no_name"

    lower_name = form_name.lower()

    # 1. Проверенный сервисный паттерн — единственный надёжный сигнал.
    #    Только здесь допустим SERVICE без разметки.
    if classify_form_by_name(form_name) == FormClass.SERVICE:
        return FormClass.SERVICE, "by_service_pattern"

    # 2. Стандартное имя объектной формы платформы с пустым tree.
    #    Это нераспарсенная объектная форма, а не диалог.
    if lower_name in PLATFORM_OBJECT_FORM_NAMES:
        return FormClass.UNKNOWN, "platform_object_name_unparsed"

    # 3. Имя намекает на сервисную форму, но подтверждения нет.
    #    ФормаНастройки отчёта содержит поля данных — это не диалог.
    for pattern in EMPTY_TREE_NAME_HINTS:
        if lower_name.startswith(pattern):
            return FormClass.UNKNOWN, "empty_tree_name_hint"

    # 4. Ничего не известно.
    return FormClass.UNKNOWN, "unparsed_empty_tree"


# ---------------------------------------------------------------------------
# Классификация форм без виджетов данных (issue #109)
# ---------------------------------------------------------------------------

def classify_no_widgets_form(
    form_name: str,
    reason: object,
) -> FormClass:
    """Cклассифицировать форму, у которой структурно подтверждено отсутствие
    виджетов данных (``UnindexedReason.NO_TABULAR_NO_WIDGETS``).

    В отличие от :func:`classify_empty_tree_form`, здесь
    ``elem_parser.classify_unindexed_form`` уже установил, что legacy JSON
    читается корректно и не содержит ни TabularField, ни InputField/ComboBox.
    Это структурное доказательство, а не предположение по имени.

    Правило (оба условия обязательны):

    1. ``reason == UnindexedReason.NO_TABULAR_NO_WIDGETS``
    2. ``classify_empty_tree_form(form_name)`` возвращает причину
       ``"by_service_pattern"`` или ``"empty_tree_name_hint"``

    → :data:`FormClass.SERVICE`

    Возвращает :data:`FormClass.UNKNOWN` если:
    - ``reason != NO_TABULAR_NO_WIDGETS``
    - имя пустое или не передано
    - имя даёт ``"platform_object_name_unparsed"`` (объектная форма платформы)
    - имя даёт ``"unparsed_empty_tree"`` (неизвестный паттерн — не угадываем)

    Параметры
    ----------
    form_name:
        Короткое имя формы (лист-часть пути).
    reason:
        Результат ``classify_unindexed_form().reason``
        (``UnindexedReason`` enum). Принимается как ``object`` для
        избежания циклического импорта; сравнивается по значению.
    """
    # Импорт здесь для избежания циклической зависимости на уровне модулей.
    # elem_parser импортирует form_classifier, поэтому form_classifier
    # не должен импортировать elem_parser на верхнем уровне.
    from v8unpack_agent.elem_parser import UnindexedReason  # noqa: PLC0415

    if reason is not UnindexedReason.NO_TABULAR_NO_WIDGETS:
        return FormClass.UNKNOWN

    _form_class, hint_reason = classify_empty_tree_form(form_name)

    if hint_reason in ("by_service_pattern", "empty_tree_name_hint"):
        return FormClass.SERVICE

    return FormClass.UNKNOWN


# ---------------------------------------------------------------------------
# Классификация по структуре привязок
# ---------------------------------------------------------------------------

def classify_form_by_bindings(elements: Iterable[dict]) -> FormClass:
    """Cклассифицировать форму по структуре привязок data_path.

    Алгоритм:
    - если data-элементов нет (Label, Group, Button и т.п.) — :data:`FormClass.SERVICE`
      (информационная/навигационная форма, поля данных по архитектуре отсутствуют);
    - если хотя бы один ``data_path`` начинается
      с ``Объект.`` (регистронезависимо) — :data:`FormClass.OBJECT`;
    - если data-элементы есть, но ни одного объектного пути — :data:`FormClass.SERVICE`.

    Параметры
    ----------
    elements:
        Итерируемая коллекция dict-элементов формы с полями
        ``"type"`` и ``"data_path"``.
    """
    data_count = 0

    for elem in elements:
        elem_type = elem.get("type") or "Unknown"

        if elem_type not in DATA_ELEMENT_TYPES:
            continue

        data_count += 1
        data_path = elem.get("data_path") or ""

        if data_path.lower().startswith(_OBJECT_BINDING_PREFIX):
            return FormClass.OBJECT

    if data_count == 0:
        # Нет полей данных вообще: Label/Group/Button/Decoration/Image.
        # Это информационная или навигационная форма — по архитектуре сервисная.
        # UNKNOWN не возвращаем: элементы есть, просто без data_path.
        return FormClass.SERVICE

    # data-элементы есть, но ни одного Объект.* → реквизиты формы, не объекта
    return FormClass.SERVICE


# ---------------------------------------------------------------------------
# Итоговая классификация
# ---------------------------------------------------------------------------

def classify_form(
    form_name: str,
    elements: Iterable[dict],
) -> FormClass:
    """Cклассифицировать форму, объединяя два критерия (OR-логика).

    Форма считается SERVICE если хотя бы один критерий даёт SERVICE.
    Форма считается OBJECT если ни один критерий не дал SERVICE и хотя бы
    один дал OBJECT.
    Иначе — UNKNOWN (элементов нет вообще).

    Параметры
    ----------
    form_name:
        Короткое имя формы (лист-часть пути).
    elements:
        Итерируемая коллекция dict-элементов формы.

    Notes
    -----
    Для форм с пустым ``tree`` используйте :func:`classify_empty_tree_form` —
    она даёт диагностическую причину вместо голого UNKNOWN.
    Для форм с ``UnindexedReason.NO_TABULAR_NO_WIDGETS`` используйте
    :func:`classify_no_widgets_form` — она учитывает структурное
    подтверждение от elem_parser.
    """
    elements = list(elements)

    if not elements:
        return FormClass.UNKNOWN

    by_name = classify_form_by_name(form_name)

    if by_name == FormClass.SERVICE:
        return FormClass.SERVICE

    by_bindings = classify_form_by_bindings(elements)

    if by_bindings == FormClass.SERVICE:
        return FormClass.SERVICE

    if by_bindings == FormClass.OBJECT:
        return FormClass.OBJECT

    return FormClass.UNKNOWN
